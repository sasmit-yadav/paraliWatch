"""Write eval/metrics.json and a readable eval/RESULTS.md from a training run."""

from __future__ import annotations

import json

import pandas as pd

from parali import config

LABELS = {
    "persistence_3d": "Fires in the cell, last 3 days",
    "neighbourhood_3d": "Fires in and around the cell, last 3 days",
    "same_days_last_year": "Fires in the same cell, same days last year",
    "history_rate": "Cell's average fires per season (earlier years)",
}


def fmt(x: float) -> str:
    return f"{x:.3f}"


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def write(results: dict, fire_counts: pd.Series) -> None:
    (config.EVAL_DIR / "metrics.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
    m = results["model"]
    lines = [
        "# Forecast results",
        "",
        "Generated by `python -m parali train`. Do not edit by hand.",
        "",
        f"**Task:** for every H3 cell (~36 km2) in Punjab and Haryana and every day, predict whether "
        f"NASA VIIRS will detect at least one fire in that cell in the next {config.HORIZON_DAYS} days.",
        "",
        f"**Split:** train {config.TRAIN_YEARS[0]}-{config.TRAIN_YEARS[-1]}, validation (early stopping, "
        f"calibration) {config.VALID_YEARS[0]}, test {config.TEST_YEARS[0]} (used once, for this report).",
        "",
        f"## Test season {config.TEST_YEARS[0]}",
        "",
        "Fire capture @10% = share of all fires in the next 3 days that fell inside the 10% of cells the "
        "method ranked highest that day. It answers: if officials could only watch 1 in 10 cells, how "
        "many fires would they cover?",
        "",
        "| Method | PR-AUC | ROC-AUC | Precision @10% | Fire capture @10% |",
        "| --- | --- | --- | --- | --- |",
        f"| **LightGBM model (uncalibrated scores, used for ranking)** | **{fmt(results['model_uncalibrated']['pr_auc'])}** | "
        f"**{fmt(results['model_uncalibrated']['roc_auc'])}** | **{pct(results['model_uncalibrated']['precision_top10pct'])}** | "
        f"**{pct(results['model_uncalibrated']['fire_capture_top10pct'])}** |",
    ]
    for key, label in LABELS.items():
        b = results["baselines"][key]
        lines.append(
            f"| Baseline: {label} | {fmt(b['pr_auc'])} | {fmt(b['roc_auc'])} | "
            f"{pct(b['precision_top10pct'])} | {pct(b['fire_capture_top10pct'])} |"
        )
    lines += [
        "",
        f"Base rate (share of cell-days with a fire in the next 3 days): {pct(m['base_rate'])}. "
        "A random ranking would score PR-AUC equal to the base rate.",
        "",
        "## Calibration",
        "",
        f"Isotonic calibration fitted on {config.VALID_YEARS[0]}. Brier score on the test season: "
        f"{fmt(m['brier'])} calibrated vs {fmt(results['model_uncalibrated']['brier'])} raw "
        "(lower is better). Calibrated probabilities are shown in the dashboard; raw scores are used "
        "for ranking because calibration merges close scores into ties.",
        "",
        "| Predicted (mean) | Observed fire rate | Cell-days |",
        "| --- | --- | --- |",
    ]
    for row in results["reliability"]:
        lines.append(f"| {pct(row['predicted'])} | {pct(row['observed'])} | {row['n']:,} |")
    lines += [
        "",
        "## By state (fairness check)",
        "",
        "| State | PR-AUC | Fire capture @10% | Base rate |",
        "| --- | --- | --- | --- |",
    ]
    for state, s in results["by_state"].items():
        lines.append(f"| {state} | {fmt(s['pr_auc'])} | {pct(s['fire_capture_top10pct'])} | {pct(s['base_rate'])} |")
    lines += [
        "",
        "Within-state fire capture ranks cells inside each state separately, so it is not directly "
        "comparable to the all-area number above.",
        "",
        "## Class imbalance trial (validation season)",
        "",
        "| Variant | PR-AUC | Fire capture @10% |",
        "| --- | --- | --- |",
    ]
    for name, s in results["imbalance_trial"].items():
        chosen = " (chosen)" if name == results["chosen"] else ""
        lines.append(f"| {name}{chosen} | {fmt(s['pr_auc'])} | {pct(s['fire_capture_top10pct'])} |")
    lines += [
        "",
        "## What the model relies on",
        "",
        "Share of total split gain (top 10 features):",
        "",
        "| Feature | Gain share |",
        "| --- | --- |",
    ]
    for name, share in list(results["importance_gain_share"].items())[:10]:
        lines.append(f"| `{name}` | {pct(share)} |")
    lines += [
        "",
        "## Fire points per season in the study area (VIIRS S-NPP, 15 Sep - 15 Dec)",
        "",
        "| Season | Fire points |",
        "| --- | --- |",
    ]
    for year, n in fire_counts.items():
        lines.append(f"| {year} | {n:,} |")
    lines += [
        "",
        "Detected fires fell about 16x between 2021 and 2025. Part of this is real reduction; part may "
        "be burning shifted to times when polar-orbiting satellites are not overhead. The model can "
        "only learn what the satellite sees. See docs/DATA.md.",
        "",
    ]
    (config.EVAL_DIR / "RESULTS.md").write_text("\n".join(lines), encoding="utf-8")
