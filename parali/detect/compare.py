"""Are the differences between burn-scar models real? Bootstrap over validation scenes.

Re-evaluates the saved models scene by scene, then resamples the 264 scenes with replacement
2,000 times and recomputes burn-class IoU for each model, giving 95% intervals for each model and
for the difference against the fine-tuned Prithvi model.

Usage: python -m parali.detect.compare <data_dir>
Writes eval/burn_scars/comparison.json and eval/burn_scars/RESULTS.md.
"""

from __future__ import annotations

import json
import os
import sys

import numpy as np
import torch

from parali.detect.models import normalise
from parali.detect.train import MODEL_DIR, OUT, build, load_split

RUNS = ["unet", "prithvi_scratch", "prithvi_frozen", "prithvi_finetune"]
REFERENCE = "prithvi_finetune"
N_BOOT = 2000


@torch.no_grad()
def per_scene_counts(model, images, masks) -> np.ndarray:
    """(n_scenes, 3): true positives, false positives, false negatives for the burn class."""
    model.eval()
    rows = []
    for i in range(0, len(images), 4):
        pred = model(normalise(torch.from_numpy(images[i:i + 4].astype(np.float32)))).argmax(1).numpy()
        for p, y in zip(pred, masks[i:i + 4]):
            v = y >= 0
            p, y = p[v] == 1, y[v] == 1
            rows.append([(p & y).sum(), (p & ~y).sum(), (~p & y).sum()])
    return np.asarray(rows, dtype=np.int64)


def iou(c: np.ndarray) -> float:
    tp, fp, fn = c.sum(0)
    return tp / (tp + fp + fn)


def main() -> None:
    data_dir = sys.argv[1]
    torch.set_num_threads(os.cpu_count() or 2)
    images, masks = load_split(os.path.join(data_dir, "validation"))
    counts = {}
    for run in RUNS:
        path = MODEL_DIR / f"{run}.pt"
        if not path.exists():
            continue
        model = build(run, weights=None)
        model.load_state_dict(torch.load(path, map_location="cpu", weights_only=True))
        counts[run] = per_scene_counts(model, images, masks)
        print(run, round(iou(counts[run]), 4), flush=True)

    rng = np.random.default_rng(0)
    idx = rng.integers(0, len(images), size=(N_BOOT, len(images)))
    boot = {run: np.array([iou(c[i]) for i in idx]) for run, c in counts.items()}
    result = {}
    for run in counts:
        entry = {
            "iou_burn": round(iou(counts[run]), 4),
            "ci95": [round(float(np.percentile(boot[run], q)), 4) for q in (2.5, 97.5)],
        }
        if run != REFERENCE and REFERENCE in boot:
            diff = boot[REFERENCE] - boot[run]
            entry[f"{REFERENCE}_minus_this"] = {
                "mean": round(float(diff.mean()), 4),
                "ci95": [round(float(np.percentile(diff, q)), 4) for q in (2.5, 97.5)],
                "share_of_resamples_reference_better": round(float((diff > 0).mean()), 4),
            }
        result[run] = entry
    (OUT / "comparison.json").write_text(json.dumps(result, indent=2))
    _table(result)
    print(json.dumps(result, indent=2))


def _table(result: dict) -> None:
    metrics = {r: json.loads((OUT / f"{r}.json").read_text())["metrics"] for r in result}
    lines = [
        "# Burn-scar segmentation results (HLS Burn Scars validation, 264 scenes)",
        "",
        "Generated by `python -m parali.detect.compare`. IoU and F1 are for the burned class.",
        "",
        "| Model | IoU (95% CI) | F1 | Precision | Recall | Trained params | Train min (CPU) |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in RUNS:
        if r not in result:
            continue
        m, e = metrics[r], result[r]
        lines.append(
            f"| {r} | {e['iou_burn']:.3f} ({e['ci95'][0]:.3f}-{e['ci95'][1]:.3f}) | {m['f1_burn']:.3f} | "
            f"{m['precision_burn']:.3f} | {m['recall_burn']:.3f} | {m['params_trained'] / 1e6:.2f} M | "
            f"{m['train_minutes']} |"
        )
    lines += ["", f"Difference vs {REFERENCE} (bootstrap over scenes, 2,000 resamples):", ""]
    for r in RUNS:
        d = result.get(r, {}).get(f"{REFERENCE}_minus_this")
        if d:
            lines.append(
                f"- {r}: {d['mean']:+.3f} IoU (95% CI {d['ci95'][0]:+.3f} to {d['ci95'][1]:+.3f}); "
                f"{REFERENCE} better in {d['share_of_resamples_reference_better']:.0%} of resamples"
            )
    (OUT / "RESULTS.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
